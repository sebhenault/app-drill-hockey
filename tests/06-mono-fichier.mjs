import { chromium } from './_pw.mjs';
const SHOT = process.env.SHOT_DIR || './tests/captures';
await (await import('node:fs')).promises.mkdir(SHOT, { recursive: true });
const b=await chromium.launch(); const ok=[],errs=[];
const check=(n,c)=>ok.push((c?'PASS':'ÉCHEC')+' — '+n);
const p=await b.newPage({viewport:{width:1440,height:900}});
p.on('pageerror',e=>errs.push('PAGEERROR: '+e.message));
p.on('console',m=>{if(m.type()==='error')errs.push('CONSOLE: '+m.text());});
p.on('request', r => { const u=new URL(r.url()); if(u.protocol!=='file:' && u.protocol!=='data:' && u.protocol!=='blob:') errs.push('REQUÊTE EXTERNE: '+r.url()); });

await p.goto('file://' + process.cwd() + '/dist/drillbuilder-hockey.html',{waitUntil:'networkidle'});
await p.waitForTimeout(1200);
check('démarre en fichier local', (await p.locator('.hero h1').count())===1);
await p.evaluate(()=>{location.hash='#/bibliotheque';});
await p.waitForTimeout(700);
check('22 exercices de démonstration', (await p.locator('.drill-card').count())===22);
await p.evaluate(()=>{location.hash='#/editeur';});
await p.waitForTimeout(700);
check('éditeur monté', (await p.locator('#rinkSvg').count())===1);
const box = await p.locator('#rinkSvg').boundingBox();
await p.locator('.ed-tools [data-tool="obj:player"]').click();
await p.mouse.click(box.x+box.width*0.4, box.y+box.height*0.5); await p.waitForTimeout(250);
check('ajout d’un joueur', (await p.evaluate(()=>document.querySelectorAll('#rinkSvg g[data-id]').length))===1);
await p.locator('.ed-title').fill('Artifact — test');
await p.locator('.ed-top .btn-primary').click(); await p.waitForTimeout(700);
check('sauvegarde locale (IndexedDB/localStorage)', (await p.locator('.toast').first().textContent()||'').includes('sauvegardé'));
await p.reload({waitUntil:'networkidle'}); await p.waitForTimeout(1200);
await p.evaluate(()=>{location.hash='#/bibliotheque';}); await p.waitForTimeout(700);
check('persistance après rechargement', (await p.locator('.drill-card').count())===23);
await p.screenshot({path:SHOT+'/20-artifact.png'});
console.log(ok.join('\n'));
console.log('--- erreurs / requêtes externes:', errs.length ? errs.join('\n') : 'aucune');
await b.close();
