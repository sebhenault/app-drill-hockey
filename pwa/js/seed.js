/* ---------- Fabrique d'exercice ---------- */
function drill(d) {
  const now = nowIso();
  return {
    id: d.id, schemaVersion: 1,
    title: d.title, summary: d.summary, description: d.description,
    objectives: d.objectives || [],
    ageGroups: d.ageGroups, difficulty: d.difficulty,
    skills: d.skills, situations: d.situations,
    playersMin: d.playersMin, playersMax: d.playersMax, goalies: d.goalies || 0,
    durationMin: d.durationMin, iceSpace: d.iceSpace, equipment: d.equipment || [],
    setup: d.setup, steps: d.steps || [], teachingPoints: d.teachingPoints || [],
    commonErrors: d.commonErrors || [], variationsEasier: d.variationsEasier || [],
    variationsHarder: d.variationsHarder || [], safety: d.safety || [],
    keywords: d.keywords || [],
    surface: d.surface, sequences: d.sequences,
    videos: d.videos || [], source: d.source || SRC.own,
    author: 'Bibliothèque DrillBuilder', visibility: 'public', isDemo: true,
    createdAt: now, updatedAt: now,
  };
}

