/* ---------- Constructeurs compacts ---------- */
const DARK = '#12212e', RED = '#d2262c', BLUE = '#1f5fd0', GREEN = '#1a8a4e', ORANGE = '#c46a00';

let _z = 0;
/** Objet du canevas. */
function o(obj, x, y, extra = {}) {
  return { id: uid('el'), kind: 'object', obj, x, y, rot: 0, scale: 1,
    color: extra.color || DARK, z: _z++, ...extra };
}
/** Tracé. */
function p(style, points, extra = {}) {
  const caps = { skate: 'arrow', backward: 'arrow', 'puck-carry': 'arrow', pass: 'arrow',
    shot: 'arrow', lateral: 'arrow', crossover: 'arrow', pivot: 'pivot', turn: 'arrow',
    check: 'check', handoff: 'tee', freehand: 'none' };
  return { id: uid('el'), kind: 'path', style, points, width: 7,
    color: extra.color || DARK, startCap: 'none', endCap: caps[style] || 'arrow', z: _z++, ...extra };
}
const seq = (name, duration, note, elements) => ({ id: uid('seq'), name, duration, note, elements });

