const DICT = { 'fr-CA': FR, en: EN };

let current = 'fr-CA';

export function setLocale(loc) {
  current = DICT[loc] ? loc : 'fr-CA';
  document.documentElement.lang = current === 'en' ? 'en' : 'fr-CA';
}
export function getLocale() { return current; }
export function availableLocales() {
  return [{ id: 'fr-CA', label: 'Français (Canada)' }, { id: 'en', label: 'English (partial)' }];
}

/** t('lib.results', {n: 4}) → « 4 exercice(s) » */
export function t(key, vars) {
  let s = (DICT[current] && DICT[current][key]) || FR[key] || key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}
